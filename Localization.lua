local LOCALE_ALIASES = {
    esMX = "esES",
}

local function ResolveLocale(locale, localizedTable)
    local resolvedLocale = LOCALE_ALIASES[locale] or locale
    return localizedTable[resolvedLocale] or localizedTable[DEFAULT_LOCALE]
end

local languageLabels = ResolveLocale(CLIENT_LOCALE, LANGUAGE_LABELS_BY_LOCALE)
local localizedStrings = ResolveLocale(CLIENT_LOCALE, LOCALIZED_STRINGS_BY_LOCALE)
local preferredAutoLabel = ResolveLocale(CLIENT_LOCALE, {
    enUS = "Automatic (preferred / client language)",
    deDE = "Automatisch (bevorzugte / Clientsprache)",
    esES = "Automático (idioma preferido / del cliente)",
    frFR = "Automatique (langue préférée / du client)",
    ruRU = "Автоматически (предпочитаемый / язык клиента)",
})

function ns.L(key)
    if key == "AUTO_LANGUAGE" and ns.UsesSurnames then
        return preferredAutoLabel
    end
    return localizedStrings[key] or key
end

function ns.GetLanguageDisplayName(lang)
    return languageLabels[lang] or lang or ns.L("UNKNOWN")
end

function ns.GetLanguageNameAliases()
    local aliases = {}
    for _, labels in pairs(LANGUAGE_LABELS_BY_LOCALE) do
        for lang, name in pairs(labels) do aliases[name] = lang end
    end
    return aliases
end
